  function normalize(ch) {
    return TRAD_MAP[ch] || ch;
  }

  function isCjk(ch) {
    const code = ch.codePointAt(0);
    return (
      (code >= 0x3400 && code <= 0x9fff) ||
      (code >= 0xf900 && code <= 0xfaff) ||
      (code >= 0x20000 && code <= 0x2ceaf)
    );
  }

  function lookup(ch) {
    const key = normalize(ch);
    const hit = CHARS[key];
    if (hit) {
      return Object.assign({ char: key, input: ch, found: true }, hit, { eraMeta: ERA[hit.era] });
    }
    return {
      char: key,
      input: ch,
      found: false,
      pinyin: "",
      meaning: "小字典裡還沒有這個字",
      era: "later",
      eraMeta: {
        label: "待發現",
        note: "甲骨文目前能確認的字大約一千多個，有些字是後來才造的，有些還在研究。",
      },
      story:
        "這個字我們還沒收進教學小字典。你可以觀察它由哪些部分組成：有沒有木、水、心、女、日？零件裡往往藏着古老的圖畫。",
    };
  }

  function parseName(raw) {
    return Array.from((raw || "").trim()).filter(isCjk).slice(0, 8);
  }

  function pickSignature(name, usedChars) {
    const chars = parseName(name).map(normalize);
    if (!chars.length) return null;
    const hasGlyph = (ch) => root.JiaguGlyphs && JiaguGlyphs.hasGlyph(ch);
    const scored = chars.map((ch, i) => {
      const hit = lookup(ch);
      let score = 0;
      if (hit.found) score += 10;
      if (hasGlyph(hit.char)) score += 42;
      if (hit.era === "oracle") score += 24;
      else if (hit.era === "bronze") score += 16;
      else if (hit.era === "seal") score += 8;
      score += i * 4;
      if (usedChars && usedChars.has(hit.char)) score -= 30;
      return { hit, score };
    });
    scored.sort((a, b) => b.score - a.score);
    return scored[0].hit;
  }

  root.JiaguChars = { lookup, normalize, isCjk, parseName, pickSignature, ERA, CHARS };
